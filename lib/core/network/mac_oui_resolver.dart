import 'dart:convert';
import 'dart:io';
import '../utils/app_storage.dart';

/// Lightweight offline OUI (Organizationally Unique Identifier) MAC resolver.
/// Resolves hardware vendor (e.g. TP-Link, Cisco, Intel, Dell, Apple, ASIX, etc.)
/// from MAC address prefixes in O(1) without requiring network connectivity.
/// Also supports loading and editing custom user mappings via mac_oui.json.
class MacOuiResolver {
  MacOuiResolver._();

  static final Map<String, String> _customOuiMap = <String, String>{};
  static File? _customStorageFile;

  /// Sets custom storage file path for unit testing.
  static void setStorageFileForTesting(File? file) {
    _customStorageFile = file;
  }

  /// Clears in-memory custom mappings (useful for testing).
  static void clearCustomMappingsForTesting() {
    _customOuiMap.clear();
  }

  /// Returns unmodifiable map of custom OUI rules.
  static Map<String, String> get customMap => Map.unmodifiable(_customOuiMap);

  /// Total count of built-in OUI entries.
  static int get totalBuiltInCount => _ouiMap.length;

  /// Total count of custom OUI entries.
  static int get totalCustomCount => _customOuiMap.length;

  /// Resolves the storage file for custom MAC OUI definitions (mac_oui.json).
  static Future<File> getStorageFile() async {
    if (_customStorageFile != null) return _customStorageFile!;

    // 1. Check if a local mac_oui.json exists in the current working directory
    final localFile = File('mac_oui.json');
    try {
      if (await localFile.exists()) {
        _customStorageFile = localFile;
        return localFile;
      }
    } catch (_) {}

    // 2. Default to app storage directory
    try {
      _customStorageFile = await AppStorage.getFile('mac_oui.json');
    } catch (_) {
      _customStorageFile = localFile;
    }
    return _customStorageFile!;
  }

  /// Initializes resolver and loads custom OUI rules from mac_oui.json.
  static Future<int> initialize({File? storageFile}) async {
    if (storageFile != null) {
      _customStorageFile = storageFile;
    }
    return loadCustomMappings();
  }

  /// Cleans raw MAC or prefix string into 6 uppercase hex characters without separators.
  static String? cleanOUI(String? raw) {
    if (raw == null) return null;
    final cleaned = raw.replaceAll(RegExp(r'[:.\-\s]'), '').toUpperCase();
    if (cleaned.length >= 6 && RegExp(r'^[0-9A-F]{6,}$').hasMatch(cleaned)) {
      return cleaned.substring(0, 6);
    }
    return null;
  }

  /// Loads custom OUI mappings from local JSON file.
  static Future<int> loadCustomMappings([File? overrideFile]) async {
    try {
      final file = overrideFile ?? await getStorageFile();
      if (!await file.exists()) {
        return 0;
      }
      final content = await file.readAsString();
      if (content.trim().isEmpty) return 0;
      final dynamic decoded = jsonDecode(content);
      final newMap = <String, String>{};
      if (decoded is Map) {
        for (final entry in decoded.entries) {
          final key = entry.key.toString().trim();
          if (key.startsWith('_')) {
            continue; // Skip comment fields like _comment
          }
          final cleaned = cleanOUI(key);
          final vendor = entry.value.toString().trim();
          if (cleaned != null && vendor.isNotEmpty) {
            newMap[cleaned] = vendor;
          }
        }
      } else if (decoded is List) {
        for (final item in decoded) {
          if (item is Map) {
            final key = (item['oui'] ?? item['mac'] ?? item['prefix'])
                ?.toString();
            final vendor = (item['vendor'] ?? item['name'])?.toString();
            final cleaned = cleanOUI(key);
            if (cleaned != null && vendor != null && vendor.trim().isNotEmpty) {
              newMap[cleaned] = vendor.trim();
            }
          }
        }
      }
      _customOuiMap.clear();
      _customOuiMap.addAll(newMap);
      return _customOuiMap.length;
    } catch (_) {
      return 0;
    }
  }

  /// Saves custom OUI mappings to JSON file with indent.
  static Future<void> saveCustomMappings([File? overrideFile]) async {
    final file = overrideFile ?? await getStorageFile();
    final data = <String, dynamic>{
      '_comment':
          'JA Remote Custom MAC OUI mappings (6 hex characters -> Vendor Name)',
      '_updatedAt': DateTime.now().toIso8601String(),
      for (final entry in _customOuiMap.entries) entry.key: entry.value,
    };
    const encoder = JsonEncoder.withIndent('  ');
    await file.writeAsString(encoder.convert(data));
  }

  /// Sets or updates a custom OUI mapping and persists it to file.
  static Future<String?> setCustomMapping(
    String macOrOui,
    String vendor, {
    File? file,
  }) async {
    final oui = cleanOUI(macOrOui);
    if (oui == null) return null;
    final cleanVendor = vendor.trim();
    if (cleanVendor.isEmpty) return null;
    _customOuiMap[oui] = cleanVendor;
    await saveCustomMappings(file);
    return oui;
  }

  /// Removes a custom OUI mapping and updates the JSON file.
  static Future<bool> removeCustomMapping(String macOrOui, {File? file}) async {
    final oui = cleanOUI(macOrOui);
    if (oui == null) return false;
    final removed = _customOuiMap.remove(oui) != null;
    if (removed) {
      await saveCustomMappings(file);
    }
    return removed;
  }

  /// Opens the mac_oui.json file directly in default system editor (Notepad on Windows).
  static Future<bool> openConfigFile() async {
    try {
      final file = await getStorageFile();
      if (!await file.exists()) {
        await saveCustomMappings(file);
      }
      if (Platform.isWindows) {
        await Process.start('notepad.exe', [file.path]);
      } else {
        await Process.start('open', [file.path]);
      }
      return true;
    } catch (_) {
      return false;
    }
  }

  /// Opens the folder containing mac_oui.json in Windows Explorer.
  static Future<bool> openConfigFolder() async {
    try {
      final file = await getStorageFile();
      final dir = file.parent;
      if (!await dir.exists()) {
        await dir.create(recursive: true);
      }
      if (Platform.isWindows) {
        await Process.start('explorer.exe', [dir.path]);
      } else {
        await Process.start('open', [dir.path]);
      }
      return true;
    } catch (_) {
      return false;
    }
  }

  /// Normalizes MAC address string to 12 uppercase hexadecimal characters without delimiters.
  static String? cleanMac(String? mac) {
    if (mac == null) return null;
    final value = mac.trim();
    if (!RegExp(
      r'^(?:[0-9a-fA-F]{12}|(?:[0-9a-fA-F]{2}:){5}[0-9a-fA-F]{2}|(?:[0-9a-fA-F]{2}-){5}[0-9a-fA-F]{2}|(?:[0-9a-fA-F]{4}\.){2}[0-9a-fA-F]{4})$',
    ).hasMatch(value)) {
      return null;
    }
    final cleaned = value.replaceAll(RegExp(r'[:.\-]'), '').toUpperCase();
    return cleaned;
  }

  /// Extracts the 6-character hex OUI prefix (3 octets) from a MAC address.
  static String? extractOui(String? mac) {
    final cleaned = cleanMac(mac);
    if (cleaned == null || cleaned.length < 6) return null;
    return cleaned.substring(0, 6);
  }

  /// Returns the hardware manufacturer / vendor name for a given MAC address,
  /// or `null` if the vendor is unknown or invalid.
  /// Custom user OUI mappings take precedence over built-in definitions.
  static String? lookup(String? mac) {
    final oui = extractOui(mac);
    if (oui == null) return null;
    // Check custom mappings first (user overrides take highest precedence)
    if (_customOuiMap.containsKey(oui)) {
      return _customOuiMap[oui];
    }
    // Multicast and locally administered/random MACs do not identify an OUI vendor.
    if ((int.parse(oui.substring(0, 2), radix: 16) & 3) != 0) return null;
    return _ouiMap[oui];
  }

  /// Returns true if the MAC address is locally administered (U/L bit = 1, e.g. randomized MAC, virtual nic).
  static bool isLocallyAdministered(String? mac) {
    final cleaned = cleanMac(mac);
    if (cleaned == null || cleaned.length < 2) return false;
    final firstByte = int.tryParse(cleaned.substring(0, 2), radix: 16);
    if (firstByte == null) return false;
    return (firstByte & 0x02) != 0;
  }

  /// Formats a friendly device title given IP, MAC, and resolved hostname.
  /// If hostname is valid and different from IP, returns the hostname (or its host prefix).
  /// If hostname is missing or equals IP, returns '[Vendor] (IP)' if vendor is known,
  /// or 'Host-IP' otherwise.
  static String resolveFriendlyTitle({
    required String ip,
    String? mac,
    String? hostname,
  }) {
    if (hostname != null &&
        hostname.trim().isNotEmpty &&
        hostname.trim() != ip) {
      final trimmed = hostname.trim();
      return trimmed.contains('.') ? trimmed.split('.')[0] : trimmed;
    }

    final vendor = lookup(mac);
    if (vendor != null && vendor.isNotEmpty) {
      return '$vendor ($ip)';
    }

    return 'PC-$ip';
  }

  /// Returns true if the vendor typically represents network infrastructure
  /// (router, switch, access point, NAS, IP camera).
  static bool isNetworkDevice(String? mac) {
    final vendor = lookup(mac);
    if (vendor == null) return false;
    const networkVendors = {
      'TP-Link',
      'Cisco',
      'Ubiquiti',
      'MikroTik',
      'D-Link',
      'Netgear',
      'Synology',
      'QNAP',
      'Hikvision',
      'Dahua',
      'Huawei',
      'ZTE',
      'H3C',
      'Mercury',
      'Mellanox',
    };
    return networkVendors.contains(vendor);
  }

